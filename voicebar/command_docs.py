"""Generate the accepted-command reference from the parser's live grammar."""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

from . import parser as grammar

# These labels explain the action produced by each live pattern. The expressions
# themselves are never copied here: both matching and rendering use parser.py.
CLAUSE_ACTIONS = {
    "press": (("press",), "keys"),
    "maximize": (("window",), "maximize"),
    "set_maximize": (("window",), "maximize"),
    "minimize_restore": (("window",), "minimize / restore"),
    "move_monitor": (("window",), "move_monitor; requires monitor suffix"),
    "snap": (("window",), "snap_left / snap_right"),
    "close": (("close_app", "tab", "window"), "app / configured site / pronoun"),
    "open": (("open_app", "open_url"), "app / configured site / domain"),
    "switch": (("switch_app", "open_url"), "app / configured site / domain"),
}
ACTION_ORDER = (
    "open_app", "switch_app", "close_app", "window", "open_url", "web_search",
    "tab", "nav", "type_text", "press", "scroll", "volume", "media", "mode",
)


def _code(value: object) -> str:
    return "`" + str(value).replace("`", r"\`") + "`"


def _cell(value: object) -> str:
    return _code(value).replace("|", r"\|")


def _choices(values) -> str:
    return ", ".join(_code(value) for value in values)


def _mapping(values: dict) -> list[str]:
    return ["| Spoken token | Value |", "| --- | --- |"] + [
        f"| {_cell(key)} | {_cell(value)} |" for key, value in values.items()
    ]


def _contract_examples(contract_file: Path) -> dict[str, list[str]]:
    spec = importlib.util.spec_from_file_location("voicebar_docs_contract", contract_file)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot load parser contract: {contract_file}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    examples: dict[str, list[str]] = {action: [] for action in ACTION_ORDER}
    for utterance, actions in module.COMMANDS:
        for action in {item["action"] for item in actions}:
            if len(examples[action]) < 3:
                examples[action].append(utterance)
    return examples


def render_commands(contract_file: Path) -> str:
    """Return deterministic Markdown; examples come from the unchanged contract."""
    if set(CLAUSE_ACTIONS) != set(grammar.CLAUSE_PATTERNS):
        raise RuntimeError("A parser clause has no command-document action label")
    examples = _contract_examples(contract_file)
    lines = [
        "# Accepted commands",
        "",
        ("Generated by `uv run python scripts/generate_commands.py` from the live "
        "patterns, token sets, and maps in `voicebar/parser.py`; examples come from "
        "`tests/test_parser_contract.py`. Do not edit this file by hand."),
        "",
        "Run `uv run python scripts/generate_commands.py --check` to detect drift.",
        "",
        ("Patterns below are Python regular expressions over normalized command "
        "tokens. Parentheses describe groups, `|` separates alternatives, `?` makes "
        "the preceding part optional, and `.+` is a nonempty target or payload. "
        "Every command must consume its complete clause; unknown or ambiguous "
        "targets make the whole plan `null`."),
        "",
    ]
    for action in ACTION_ORDER:
        lines.extend([f"## {action}", "", "| Accepted grammar | Result / detail |", "| --- | --- |"])
        for pattern, result in grammar.FIXED:
            if result["action"] == action:
                lines.append(f"| {_cell(pattern)} | {_cell(json.dumps(result, sort_keys=True))} |")
        for name, (actions, description) in CLAUSE_ACTIONS.items():
            if action in actions:
                lines.append(f"| {_cell(grammar.CLAUSE_PATTERNS[name].pattern)} | {description} |")
        if action == "tab":
            lines.append(f"| {_cell(grammar.NEW_TAB.pattern)} | new; bare `tab` is rejected |")
        if action == "scroll":
            lines.append(f"| {_cell(grammar.SCROLL.pattern)} | up / down; amount mapping below |")
        if action == "type_text":
            for verb in grammar.TYPE_VERBS:
                lines.append(f"| {_cell(verb + ' <text>')} | raw text; optional submit suffix below |")
        if action == "web_search":
            search = grammar.SEARCH_VERB
            templates = [
                f"{search} <query> [{grammar.SEARCH_TRAILING}]",
                *[f"{search} {word} <query>" for word in grammar.SEARCH_PREPOSITIONS],
                f"{search} <engine> {grammar.ENGINE_QUERY_JOINER} <query>",
                " ".join(grammar.LOOKUP_PREFIX) + " <query>",
                f"{grammar.DEFAULT_ENGINE} <query>",
            ]
            for template in templates:
                lines.append(f"| {_cell(template)} | engine defaults to {_cell(grammar.DEFAULT_ENGINE)} |")
            lines.append(f"| {_cell('<query> ' + grammar.ENGINE_SUFFIX + ' <engine>')} | "
                         "optional query suffix selects a configured engine |")
        lines.extend(["", "Contract examples: " + _choices(examples[action]) + ".", ""])
        if action in {"open_app", "switch_app", "open_url"}:
            lines.extend([
                ("The target can use these suffixes. App monitor suffixes add a "
                "`window/move_monitor` action; site/domain monitor suffixes are rejected."),
                "",
                *[f"- {_code(pattern.pattern)}" for pattern in
                  (grammar.MON_TAIL, grammar.TAB_TAIL, grammar.BROWSER_TAIL)],
                "",
            ])
        if action == "window":
            lines.extend([
                (f"Omitted targets and {_code(grammar.PRONOUN)} refer to the app "
                "named earlier in this utterance, then `last_app`, then `active`."),
                "",
                "Monitor suffix: " + _code(grammar.MON_TAIL.pattern) + ".",
                "",
                *_mapping(grammar.MON_MAP),
                "",
            ])
        if action == "type_text":
            lines.extend([
                ("Typing and searching consume the rest of the utterance, including "
                "command-looking words. Typing strips one of these nonempty-payload "
                "suffixes and sets `submit=true`:"),
                "",
                *["- " + _code(" ".join(tail)) for tail in grammar.SUBMIT_TAILS],
                "",
                ("Payloads preserve raw case and internal punctuation. They trim "
                "spaces, periods, commas, semicolons and colons at the end, and "
                "spaces, commas, semicolons and colons at the start; `?` and `!` survive."),
                "",
            ])
        if action == "press":
            lines.extend([
                *_mapping(grammar.KEYS), "",
                "Ignored key filler: " + _choices(sorted(grammar.KEY_FILLER)) + ".",
                "",
                "Other key tokens: " + _code(grammar.KEY_ATOM.pattern) + "; "
                + _code(grammar.KEY_NUMBER_PREFIX + " <digits>") + "; "
                + _choices(grammar.KEY_PAGE_PREFIX + " " + direction
                           for direction in grammar.KEY_PAGE_DIRECTIONS) + ". "
                "Keys join with `+`; any unknown token rejects the clause.", "",
            ])
        if action == "scroll":
            lines.extend([*_mapping({"(omitted)" if key is None else key: value
                                     for key, value in grammar.AMOUNT.items()}), ""])
    lines.extend([
        "## Shared target resolution", "",
        "Leading articles: " + _choices(sorted(grammar.ARTICLES)) + ".",
        "",
        "Target noise removed before a second resolution attempt: leading "
        + _choices(sorted(grammar.NOISE_LEAD)) + "; trailing "
        + _choices(sorted(grammar.NOISE_TRAIL)) + ".", "",
        "Resolution tries configured aliases, exact app names, configured sites, "
        "spoken/literal domains, whole-word app subsets, then full-string app "
        "similarity. Alias and exact-name matching ignores spaces, case, and "
        "token-edge punctuation using " + _code(grammar._EDGE.pattern) + ". "
        "Duplicate normalized app names are ambiguous and reject the utterance "
        "before command splits can reinterpret the target. Domain grammar: "
        + _code(grammar.DOMAIN.pattern) + "; spoken `dot` is accepted. "
        "Fuzzy minimum: " + str(grammar.FUZZY_MIN) + "; required lead over runner-up: "
        + str(grammar.MARGIN) + ".", "",
        "## Politeness and chaining", "",
        "Repeated removable leading phrases: "
        + _choices(" ".join(words) for words in grammar.LEAD) + ".", "",
        "Repeated removable trailing phrases: "
        + _choices(" ".join(words) for words in grammar.TRAIL) + ".", "",
        "Whole clauses are attempted before splits. Joins: "
        + _choices(" ".join(words) for words in grammar.CHAIN_JOINERS)
        + ", punctuation boundaries, or any word boundary. All clauses must parse. "
        "A following bare target can inherit `open`, `switch`, or `close`. "
        "Non-payload command limit: " + str(grammar.MAX_COMMAND_WORDS) + " tokens.", "",
        "`app_action` is reserved for Stage 7 and has no Stage 1 grammar.", "",
    ])
    return "\n".join(lines)
